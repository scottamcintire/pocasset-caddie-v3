#!/usr/bin/env python3
"""Write data/holes/holeNN/camera.json from the APPROVED camera approach (VISUAL_BASELINE_v1.0.json), scaled to the hole.
  python3 -I tools/make_camera.py --hole N
* Tee view: from behind the owner's primary tee (Green; else Blue; else the mapped tee nearest the card's Green yardage).
* Distances back/up and the margins scale with the look-from-tee-to-green distance L relative to Hole 2 (L2 = 336 m),
  so Hole 2 gets exactly its approved values; clamped so par 3s and long par 5s stay readable.
* Approach: the approved values, with the look-from distance capped at 75% of L for short holes.
Never overwrites an existing camera.json (manual record) unless --force."""
import argparse, json, math, os, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..')); sys.path.insert(0, os.path.join(ROOT, 'tools'))
import pcv3
ap = argparse.ArgumentParser(); ap.add_argument('--hole', type=int, required=True); ap.add_argument('--force', action='store_true'); a = ap.parse_args()
d = pcv3.p('data', 'holes', 'hole%02d' % a.hole); out = os.path.join(d, 'camera.json')
if os.path.exists(out) and not a.force: sys.exit('camera.json exists (manual record); not overwritten')
h = json.load(open(os.path.join(d, 'hole.json'))); fc = json.load(open(os.path.join(d, 'features.geojson')))['features']
tees = h['tees']; pick = None
for want in ('Green', 'Blue'):
    c = [t for t in tees if want in t['tee_sets']]
    if c: pick = c[0]; why = want; break
if not pick:
    if not tees: sys.exit('STOP: no mapped tee on hole %d' % a.hole)
    pick = min(tees, key=lambda t: abs(t['measured_yards'] - h['card_yards']['Green'])); why = 'nearest to the Green card yardage'
L = pick['measured_yards'] * 0.9144; k = L / 336.0
cl = lambda x, lo, hi: max(lo, min(hi, x))
tee = {"description": "Full-hole flyover from behind the %s tee (%s), looking down the hole to the green" % (pick['tee_sets'][0] if pick['tee_sets'] else pick['feature_id'], why),
       "look_from_feature": pick['feature_id'], "look_to": "green",
       "back_m": round(cl(95 * k, 55, 125)), "height_m": round(cl(105 * k, 65, 140)), "show_behind_tee_m": round(cl(22 * k, 14, 30)),
       "show_beyond_green_m": round(cl(70 * k, 40, 90)), "side_shift_m": 0, "texture_px_per_m": 7, "output_height_px": 1440}
appr = {"description": "Approach: green complex from about %d yd out on the approach line" % round(min(100, 0.75 * L) / 0.9144 + 25 / 0.9144),
        "look_from_green_m": round(min(100, 0.75 * L)), "look_to": "green", "back_m": 25, "height_m": 60, "show_behind_tee_m": -5,
        "show_beyond_green_m": 32, "side_shift_m": 0, "texture_px_per_m": 24, "output_height_px": 1400}
cam = {"schema": "pocasset-v3/camera@1", "hole": a.hole,
       "note": "Manual record (camera only; never geography). Generated by tools/make_camera.py from the approved camera approach v1.0, scaled by L=%.0f m (Hole 2 = 336 m). Adjust by hand if a hole needs it; record why." % L,
       "views": {"tee": tee, "approach": appr}}
json.dump(cam, open(out, 'w'), indent=1); open(out, 'a').write('\n')
print('camera hole %d: tee %s (%s), back %d up %d; approach from %d m' % (a.hole, pick['feature_id'], why, tee['back_m'], tee['height_m'], appr['look_from_green_m']))
